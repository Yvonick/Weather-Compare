import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const bucket = "https://met-office-land-observations-data.s3.eu-west-2.amazonaws.com/";
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const decodeXml = (value) => value
  .replaceAll("&amp;", "&")
  .replaceAll("&lt;", "<")
  .replaceAll("&gt;", ">");

async function latestCanonicalPrefix() {
  const response = await fetch(`${bucket}?list-type=2&delimiter=/`);
  if (!response.ok) throw new Error(`Met Office directory listing failed with ${response.status}`);
  const xml = await response.text();
  const prefixes = [...xml.matchAll(/<Prefix>([^<]+)<\/Prefix>/g)].map((match) => decodeXml(match[1]));
  const canonical = prefixes.filter((prefix) => /^\d{12}_\d{10}00_\d{10}59\/$/.test(prefix));
  if (!canonical.length) throw new Error("No canonical hourly Met Office directory was found");
  return canonical.sort().at(-1);
}

async function stationKeys(prefix) {
  const response = await fetch(`${bucket}?list-type=2&prefix=${encodeURIComponent(prefix)}`);
  if (!response.ok) throw new Error(`Met Office station listing failed with ${response.status}`);
  const xml = await response.text();
  return [...xml.matchAll(/<Key>([^<]+\.csv)<\/Key>/g)].map((match) => decodeXml(match[1]));
}

function parseStation(key, text) {
  const lines = text.split(/\r?\n/).filter(Boolean);
  if (lines.length < 2) return null;
  const headers = lines[0].split("|");
  const values = lines[1].split("|");
  const get = (...names) => {
    const index = headers.findIndex((header) => names.includes(header));
    return index >= 0 ? values[index] : "";
  };
  const latitude = Number(get("latitude"));
  const longitude = Number(get("longitude"));
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return null;
  return {
    id: path.basename(key, ".csv").match(/_([a-f0-9-]{36})$/i)?.[1] || path.basename(key, ".csv"),
    name: get("name") || path.basename(key, ".csv"),
    latitude,
    longitude,
    filename: path.basename(key)
  };
}

async function fetchStation(key) {
  const response = await fetch(`${bucket}${key}`, { headers: { Range: "bytes=0-16383" } });
  if (!response.ok && response.status !== 206) return null;
  return parseStation(key, await response.text());
}

const prefix = await latestCanonicalPrefix();
const keys = await stationKeys(prefix);
const stations = [];
for (let index = 0; index < keys.length; index += 12) {
  const batch = await Promise.all(keys.slice(index, index + 12).map(fetchStation));
  stations.push(...batch.filter(Boolean));
}
stations.sort((left, right) => left.name.localeCompare(right.name));

const output = `/* Generated by scripts/update-uk-stations.mjs from the Met Office open-data bucket. */\nexport const UK_STATIONS = Object.freeze(${JSON.stringify(stations, null, 2)});\n`;
await mkdir(path.join(projectRoot, "server"), { recursive: true });
await writeFile(path.join(projectRoot, "server", "uk-stations.js"), output, "utf8");
console.log(`Wrote ${stations.length} UK stations from ${prefix}`);
